type I18n = { language: Language; setLanguage: (language: Language) => void; t: (text: string) => string }
const Context = createContext<I18n>({ language:'en', setLanguage:()=>{}, t:(text)=>text })
export function I18nProvider({children}:{children:ReactNode}) { const [language,setLanguageState]=useState<Language>(()=>localStorage.getItem('machinerycrm-language')==='ar'?'ar':'en'); const setLanguage=(value:Language)=>{setLanguageState(value);localStorage.setItem('machinerycrm-language',value)}; useEffect(()=>{document.documentElement.lang=language;document.documentElement.dir=language==='ar'?'rtl':'ltr';document.documentElement.style.fontFamily=language==='ar'?'Tahoma, Arial, sans-serif':''},[language]); const value=useMemo(()=>({language,setLanguage,t:(text:string)=>language==='ar'?(translations[text]||text):text}),[language]);return <Context.Provider value={value}>{children}</Context.Provider> }
export function useI18n(){return useContext(Context)}
