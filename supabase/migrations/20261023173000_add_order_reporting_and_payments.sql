CREATE TABLE public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  branch_id uuid NOT NULL REFERENCES public.locations(id) ON DELETE RESTRICT,
  account_id uuid NOT NULL REFERENCES public.accounts(id) ON DELETE RESTRICT,
  created_by uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT DEFAULT auth.uid(),
  process text NOT NULL DEFAULT 'sale' CHECK (process IN ('sale','rental','service','parts','other')),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','in_progress','fulfilled','cancelled')),
  total_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
  notes text,
  expected_completion_date date,
  rental_start_date date,
  rental_end_date date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.order_payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  amount numeric(14,2) NOT NULL CHECK (amount > 0),
  paid_at timestamptz NOT NULL DEFAULT now(),
  notes text,
  recorded_by uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_orders_branch ON public.orders(branch_id);
CREATE INDEX idx_orders_account ON public.orders(account_id);
CREATE INDEX idx_orders_status ON public.orders(status);
CREATE INDEX idx_orders_created ON public.orders(created_at DESC);
CREATE INDEX idx_order_payments_order ON public.order_payments(order_id);
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_payments ENABLE ROW LEVEL SECURITY;
CREATE TRIGGER orders_updated_at BEFORE UPDATE ON public.orders FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE POLICY orders_select ON public.orders FOR SELECT TO authenticated USING (private.current_user_role() IN ('admin','sales','operations','service','parts'));
CREATE POLICY orders_insert ON public.orders FOR INSERT TO authenticated WITH CHECK (private.current_user_role() IN ('admin','sales','operations') AND created_by=(select auth.uid()));
CREATE POLICY orders_update ON public.orders FOR UPDATE TO authenticated USING (private.current_user_role() IN ('admin','sales','operations')) WITH CHECK (private.current_user_role() IN ('admin','sales','operations'));
CREATE POLICY orders_delete ON public.orders FOR DELETE TO authenticated USING (private.current_user_role()='admin');
CREATE POLICY order_payments_select ON public.order_payments FOR SELECT TO authenticated USING (EXISTS (SELECT 1 FROM public.orders o WHERE o.id=order_payments.order_id));
CREATE POLICY order_payments_insert ON public.order_payments FOR INSERT TO authenticated WITH CHECK (private.current_user_role() IN ('admin','sales','operations') AND recorded_by=(select auth.uid()) AND EXISTS (SELECT 1 FROM public.orders o WHERE o.id=order_payments.order_id));
CREATE POLICY order_payments_update ON public.order_payments FOR UPDATE TO authenticated USING (private.current_user_role() IN ('admin','sales','operations')) WITH CHECK (private.current_user_role() IN ('admin','sales','operations'));
GRANT SELECT,INSERT,UPDATE,DELETE ON public.orders,public.order_payments TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.orders_order_number_seq TO authenticated;